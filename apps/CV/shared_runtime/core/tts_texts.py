def _apply_model_event_defaults(texts: dict) -> dict:
    defaults = {
        "checked_in_stare": MODEL_CHECKED_IN_STARE_TEXTS,
        "stranger_stare": MODEL_STRANGER_STARE_TEXTS,
    }
    for event_type, model_defaults in defaults.items():
        for model_key, values in model_defaults.items():
            model_texts = texts.get(model_key)
            if isinstance(model_texts, dict) and not model_texts.get(event_type):
                model_texts[event_type] = list(values)
    return texts


TTS_TEXTS: dict[str, dict[str, list[str]]] = _apply_model_event_defaults(
    merge_daily_texts(DEFAULT_TTS_TEXTS)
)


def reload_daily_texts() -> None:
    refresh_texts(DEFAULT_TTS_TEXTS, TTS_TEXTS)
    _apply_model_event_defaults(TTS_TEXTS)
